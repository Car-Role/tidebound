// Writes server/game/modules.manifest.js: the files in each wildcard folder (server/game/wildcards.js).
// Usage: npm run manifest            (rewrites the manifest)
//        node scripts/gen-module-manifest.js --check   (exit 1 when the checked-in manifest is stale)

import { readdirSync, readFileSync, writeFileSync, existsSync } from 'node:fs';
import { join, dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { WILDCARDS } from '../server/game/wildcards.js';

const GAME_DIR = join(dirname(fileURLToPath(import.meta.url)), '..', 'server', 'game');
export const MANIFEST_PATH = join(GAME_DIR, 'modules.manifest.js');

export function scanWildcards() {
  const out = {};
  for (const [key, { dir, match }] of Object.entries(WILDCARDS)) {
    let files = [];
    try { files = readdirSync(join(GAME_DIR, dir), { withFileTypes: true }).filter((d) => d.isFile()).map((d) => d.name); } catch { files = []; }
    out[key] = files.filter((f) => match.test(f)).sort();
  }
  return out;
}

export function renderManifest(lists = scanWildcards()) {
  const lines = [
    '// GENERATED by scripts/gen-module-manifest.js (npm run manifest). Do not edit by hand.',
    '// The files server/game/loader.js imports from each wildcard folder; a static list so the loader also runs in',
    '// the browser (no readdir). npm test checks this list against the folders.',
    '',
    'export const WILDCARD_FILES = Object.freeze({',
  ];
  for (const [key, files] of Object.entries(lists)) {
    lines.push(`  ${key}: Object.freeze([`);
    for (const f of files) lines.push(`    '${f}',`);
    lines.push('  ]),');
  }
  lines.push('});', '');
  return lines.join('\n');
}

const isMain = !!process.argv[1] && fileURLToPath(import.meta.url) === resolve(process.argv[1]);
if (isMain) {
  const text = renderManifest();
  const current = existsSync(MANIFEST_PATH) ? readFileSync(MANIFEST_PATH, 'utf8') : '';
  if (process.argv.includes('--check')) {
    if (current !== text) { console.error('modules.manifest.js is stale: run npm run manifest'); process.exit(1); }
    console.log('modules.manifest.js is up to date');
  } else if (current !== text) {
    writeFileSync(MANIFEST_PATH, text);
    console.log('wrote', MANIFEST_PATH);
  } else console.log('modules.manifest.js already up to date');
}
